// Renders the generated wrangler config: the committed wrangler.toml's Worker settings, the CONTROL database, and
// one DB_T<id> binding per vendor database that exists (provisioning vendors included; the Worker answers 503 for
// any vendor that isn't active). Vendor names never go into git: this file is written to .wrangler-generated/.
import { readFileSync } from "node:fs";
import { join, relative } from "node:path";

export const LOCAL_CONTROL = { name: "venstock-local-control", id: "local-control" };
export const localVendorDb = (id) => ({ name: `venstock-local-t${id}`, id: `local-t${id}` });
export const remoteVendorDbName = (id) => `venstock-dev-t${id}`;
import { vendorBinding } from "../../src/lib/tenant.js"; // one definition, shared with the Worker
export { vendorBinding };

// Minimal reader for the committed wrangler.toml: top-level keys, [vars], [dev], [[d1_databases]] and [[routes]].
export function readBaseToml(path) {
  const text = readFileSync(path, "utf8");
  const top = {}, vars = {}, dev = {}, d1 = [], routes = [];
  let section = "";
  let current = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/\s+#.*$/, "").trim();
    if (!line || line.startsWith("#")) continue;
    if (line.startsWith("[")) {
      section = line;
      current = line === "[[d1_databases]]" || line === "[[routes]]" ? {} : null;
      if (current) (line === "[[routes]]" ? routes : d1).push(current);
      continue;
    }
    const kv = line.match(/^([A-Za-z_]+)\s*=\s*(?:"([^"]*)"|(\S+))$/);
    if (!kv) continue;
    const value = kv[2] ?? kv[3];
    if (current) current[kv[1]] = value;
    else if (section === "") top[kv[1]] = value;
    else if (section === "[vars]") vars[kv[1]] = value;
    else if (section === "[dev]") dev[kv[1]] = value;
  }
  return { top, vars, dev, d1, routes };
}

// wrangler.toml's BASE_DOMAIN is the PRODUCTION vendor domain; local configs always use "localhost". Before anything
// remote, it must be a real domain with a wildcard route for it, or a deploy would answer 404 everywhere (or never
// receive a request). Returns what's wrong, or null.
export function productionDomainProblem(base) {
  const d = String(base.vars.BASE_DOMAIN || "");
  if (!/^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$/.test(d) || /(^|\.)localhost$/.test(d)) {
    return `set BASE_DOMAIN in wrangler.toml's [vars] to the vendor domain (found ${JSON.stringify(d)}).`;
  }
  if (!base.routes.some((r) => r.pattern === `*.${d}/*` && r.zone_name)) {
    return `add a [[routes]] block to wrangler.toml with pattern = "*.${d}/*" and zone_name = "<the zone>".`;
  }
  return null;
}

// A route pattern is exactly "*.<domain>/*" (the vendor wildcard); nothing else is written into the config.
const pattern = (p) => {
  if (!/^\*\.[a-z0-9.-]+\/\*$/.test(String(p))) throw new Error(`refusing to write an unexpected route pattern into the config: ${p}`);
  return `"${p}"`;
};
const str = (s) => {
  if (!/^[\w.:\-/ ]*$/.test(String(s))) throw new Error(`refusing to write unexpected characters into the config: ${s}`);
  return `"${s}"`;
};
const rel = (from, to) => relative(from, to).split("\\").join("/") || ".";

// root: the repo; outDir: where the file will be written (paths are made relative to it);
// control: { name, id }; vendors: [{ id, db_name, db_id }]; migrationsRoot: dir holding control/ and vendor/.
// target: "local" (BASE_DOMAIN = localhost, no routes) or "remote" (wrangler.toml's BASE_DOMAIN and [[routes]]).
export function renderConfig({ root, outDir, control, vendors, migrationsRoot = join(root, "migrations"), target = "local" }) {
  const base = readBaseToml(join(root, "wrangler.toml"));
  const vars = { ...base.vars, ...(target === "local" ? { BASE_DOMAIN: "localhost" } : {}) };
  const lines = [
    "# GENERATED by scripts/ (build-config / migrate / create-tenant). Do not edit or commit.",
    `# Paths are relative to this file. Vendors: ${vendors.length}.`,
    `name = ${str(base.top.name)}`,
    `main = ${str(rel(outDir, join(root, base.top.main || "src/worker.js")))}`,
    `compatibility_date = ${str(base.top.compatibility_date)}`,
    "# Only the vendor domain's wildcard route serves the Worker: no *.workers.dev address, no preview URLs.",
    "workers_dev = false",
    "preview_urls = false",
    "",
    "[assets]",
    `directory = ${str(rel(outDir, join(root, "public")))}`,
    'binding = "ASSETS"',
    "run_worker_first = true",
    "",
    "[dev]",
    `port = ${Number(base.dev.port) || 8788}`,
    "",
    "[vars]",
    ...Object.entries(vars).map(([k, v]) => `${k} = ${str(v)}`),
    ...(target === "remote" ? base.routes.flatMap((r) => ["", "[[routes]]", `pattern = ${pattern(r.pattern)}`, `zone_name = ${str(r.zone_name)}`]) : []),
    // Workers Logs on the deployed Worker: what it logs (method, path, vendor id, error; never request bodies) is kept
    // and searchable in the dashboard. Local runs print to the terminal and don't need it.
    ...(target === "remote" ? ["", "[observability]", "enabled = true"] : []),
    "",
    "[[d1_databases]]",
    'binding = "CONTROL"',
    `database_name = ${str(control.name)}`,
    `database_id = ${str(control.id)}`,
    `migrations_dir = ${str(rel(outDir, join(migrationsRoot, "control")))}`,
  ];
  const seen = new Set();
  for (const v of vendors) {
    if (!Number.isInteger(v.id) || v.id < 1) throw new Error(`bad vendor id ${v.id}`);
    if (seen.has(v.id)) throw new Error(`vendor ${v.id} listed twice`);
    seen.add(v.id);
    if (!v.db_id) continue; // database not created yet: nothing to bind
    lines.push("", "[[d1_databases]]", `binding = ${str(vendorBinding(v.id))}`,
      `database_name = ${str(v.db_name)}`, `database_id = ${str(v.db_id)}`,
      `migrations_dir = ${str(rel(outDir, join(migrationsRoot, "vendor")))}`);
  }
  return lines.join("\n") + "\n";
}
